import {readdir, readFile, writeFile} from "node:fs/promises";
import {dirname, join, resolve} from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const localePattern = /^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/;

function leafPaths(value, prefix = "") {
  if (typeof value === "string") return [prefix];
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`Invalid message value at ${prefix || "<root>"}`);
  }
  return Object.entries(value).flatMap(([key, nested]) =>
    leafPaths(nested, prefix ? `${prefix}.${key}` : key)
  );
}

export async function discoverLocales(messagesDirectory) {
  const entries = await readdir(messagesDirectory, {withFileTypes: true});
  const locales = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => entry.name.slice(0, -5))
    .filter((locale) => localePattern.test(locale))
    .sort((left, right) => {
      if (left === "en") return -1;
      if (right === "en") return 1;
      return left.localeCompare(right);
    });

  if (!locales.includes("en")) {
    throw new Error("messages/en.json is required as the default locale");
  }

  const defaultMessages = JSON.parse(
    await readFile(join(messagesDirectory, "en.json"), "utf8")
  );
  const requiredPaths = leafPaths(defaultMessages).sort();

  for (const locale of locales) {
    const messages = JSON.parse(
      await readFile(join(messagesDirectory, `${locale}.json`), "utf8")
    );
    const localePaths = leafPaths(messages).sort();
    if (
      localePaths.length !== requiredPaths.length ||
      localePaths.some((path, index) => path !== requiredPaths[index])
    ) {
      throw new Error(
        `messages/${locale}.json must contain the same message keys as messages/en.json`
      );
    }
  }

  return locales;
}

export async function generateLocaleManifest({
  messagesDirectory,
  outputFile,
}) {
  const locales = await discoverLocales(messagesDirectory);
  const source = [
    "// Generated by scripts/generate-locales.mjs. Do not edit manually.",
    `export const locales = ${JSON.stringify(locales)} as const;`,
    "export type AppLocale = (typeof locales)[number];",
    "",
  ].join("\n");
  await writeFile(outputFile, source, "utf8");
  return locales;
}

const scriptPath = fileURLToPath(import.meta.url);
if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  const root = resolve(dirname(scriptPath), "..");
  const messagesDirectory = process.argv[2]
    ? resolve(process.argv[2])
    : join(root, "messages");
  const outputFile = process.argv[3]
    ? resolve(process.argv[3])
    : join(root, "i18n", "locales.generated.ts");
  const locales = await generateLocaleManifest({
    messagesDirectory,
    outputFile,
  });
  console.log(`Generated locale manifest: ${locales.join(", ")}`);
}
